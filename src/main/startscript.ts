import { promises as fs } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { UTF8_CONSOLE_FLAGS } from '../shared/jvmArgs'
import type { ServerConfig } from '../shared/types'
import type { ServerLayout } from './layout'

/**
 * 生成启动脚本。
 *
 * 用途是「手里能有一份可以直接双击、也能贴给别人看的东西」：
 * 服务器起不来的时候，双击它就能看到 Java 的原话是什么，
 * 不用去猜是 CraftDesk 的问题还是服务端自己的问题。
 *
 * 两个刻意的选择：
 *
 * 1. **脚本内容只用 ASCII**。Windows 的 cmd 按当前代码页解析 .bat，
 *    中文注释在 GBK/UTF-8 之间来回倒腾，很容易变成一行乱码把命令吃掉。
 *    文件名也一样，就叫 start.bat。
 * 2. **生成脚本不等于改启动方式**。CraftDesk 默认还是用参数里的 jar 启动，
 *    这样界面上的内存、JVM 参数才是生效的那一份；脚本里记的是生成那一刻
 *    的值，改完设置得重新生成。启动方式那一栏可以手动切到脚本。
 */

export interface StartScriptResult {
  /** 文件名，如 start.bat */
  file: string
  /** 相对服务器根目录的路径 */
  relPath: string
  /** 绝对路径 */
  absPath: string
  content: string
}

/** 把参数拼成一行命令行，顺带做必要的引号处理 */
function quote(p: string): string {
  return /\s/.test(p) ? `"${p}"` : p
}

/**
 * MCDReforged 托管的服务器要起的是 MCDR 自己，不是服务端核心。
 * 内存那些参数在 MCDR 的 config.yml 里，脚本里再写一遍只会误导人。
 */
function buildCommand(cfg: ServerConfig, layout: ServerLayout, coreRel: string): string {
  if (cfg.mcdr && cfg.pythonPath) {
    return `${quote(cfg.pythonPath)} -X utf8 -m mcdreforged`
  }

  /*
   * 脚本会先 cd 进核心目录，所以这里的路径都要按「相对核心目录」来写。
   * 配置里的 jar / 参数文件是相对服务器根目录的（比如 MCDR 布局下的
   * server/server.jar），照着原样写进去、又在 server/ 里执行，就会变成
   * server/server.jar —— 找不到文件。核心目录外的路径直接用绝对路径。
   */
  const coreAbs = join(cfg.dir, coreRel)
  const relCore = (p: string): string => {
    const abs = join(cfg.dir, p)
    const rel = relative(coreAbs, abs)
    if (!rel || rel.startsWith('..')) return abs
    return rel.split(sep).join('/')
  }

  const java = quote(cfg.javaPath || 'java')
  const target = cfg.launchArgs
    ? `@${quote(relCore(cfg.launchArgs))}`
    : `-jar ${quote(relCore(cfg.jar || ''))}`
  const args = [
    `-Xms${cfg.memoryMin}M`,
    `-Xmx${cfg.memoryMax}M`,
    ...cfg.jvmArgs.split(/\s+/).filter(Boolean),
    // 和 CraftDesk 自己启动时用同一套编码参数：不然双击脚本和从界面启动
    // 出来的中文日志会不一样
    ...UTF8_CONSOLE_FLAGS,
    target,
    ...cfg.serverArgs.split(/\s+/).filter(Boolean)
  ]
  return [java, ...args].join(' ')
}

export function buildStartScript(
  cfg: ServerConfig,
  layout: ServerLayout
): { file: string; content: string } {
  const win = process.platform === 'win32'
  const file = win ? 'start.bat' : 'start.sh'
  // MCDR 自己会切到 working_directory，脚本保持在根目录跑
  const coreRel = cfg.mcdr ? '' : layout.coreRel
  const cmd = buildCommand(cfg, layout, coreRel)

  // 核心在子目录里（MCDReforged 那种）就先切进去，否则工作目录不对，
  // 服务端会在外层生成 world 之类的文件
  const cd = coreRel ? `cd ${quote(coreRel)}` : null

  const lines = win
    ? [
        '@echo off',
        'rem Generated by CraftDesk. Re-generate it after changing memory or JVM args.',
        'rem Double-click to run the server in a console window so you can see errors.',
        'chcp 65001 >nul',
        'cd /d "%~dp0"',
        ...(cd ? [cd] : []),
        'echo Starting server in %CD%',
        cmd,
        'echo.',
        'echo Server exited with code %ERRORLEVEL%.',
        'pause'
      ]
    : [
        '#!/bin/sh',
        '# Generated by CraftDesk. Re-generate it after changing memory or JVM args.',
        'cd "$(dirname "$0")" || exit 1',
        ...(cd ? [cd] : []),
        'echo "Starting server in $(pwd)"',
        cmd,
        'echo "Server exited with code $?"'
      ]

  return { file, content: lines.join(win ? '\r\n' : '\n') + '\n' }
}

/**
 * 写启动脚本。已经存在的话返回值里 content 不变、直接覆盖——
 * 这个文件是 CraftDesk 生成的，重新生成就是在修它。
 */
export async function writeStartScript(
  cfg: ServerConfig,
  layout: ServerLayout
): Promise<StartScriptResult> {
  const { file, content } = buildStartScript(cfg, layout)
  const absPath = join(cfg.dir, file)
  await fs.mkdir(cfg.dir, { recursive: true })
  await fs.writeFile(absPath, content, 'utf-8')
  if (process.platform !== 'win32') {
    await fs.chmod(absPath, 0o755).catch(() => undefined)
  }
  return { file, relPath: file, absPath, content }
}
